/**
 * ABI for FeeRouter v3 — CCTP V2, hardened + upgraded.
 *
 * v3.1 patch: approve(tokenMessenger, 0) approval reset is now wrapped in
 * try/catch so it is best-effort and never reverts the bridge tx. This fixes
 * a CALL_EXCEPTION on Arc Testnet where the system USDC (0x3600…0000) reverts
 * on approve(spender, 0) without a revert reason.
 */
